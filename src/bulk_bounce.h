#ifndef BULK_BOUNCE_H
#define BULK_BOUNCE_H

#include <stdint.h>

/*
 * Общий bounce-буфер для НАТИВНЫХ bulk-обменов FatFs <-> гостевая память:
 * строковый PIO контроллера IDE (ide.c) и bulk-команды EMULINK (pc.c).
 *
 * Зачем вообще копия. FatFs требует линейный нативный буфер, а гостевая
 * память адресуется только через pload8/pstore8 (банкование EMS, окно
 * VGA), поэтому копию убрать нельзя. Держать её на стеке нельзя тем
 * более: у core0 стека мало, а эти пути вызываются из обработчиков
 * портов, уже находящихся внутри такта эмуляции.
 *
 * ГРАНИЦЫ ПРИМЕНИМОСТИ - ЧИТАТЬ ПЕРЕД ИСПОЛЬЗОВАНИЕМ.
 *
 * Буфер один на всех, и это безопасно РОВНО ПОТОМУ, что все его текущие
 * пользователи удовлетворяют трём условиям сразу:
 *
 *   1) синхронный обработчик порта ввода-вывода: один такт эмуляции
 *      порождает ровно один такой вызов;
 *   2) внутри работы с буфером управление не возвращается в цикл
 *      эмуляции (f_read/f_write из FatFs синхронны);
 *   3) исполнение только на core0 - core1 занят VGA и аудио
 *      (main.c: core1_entry) и к этим путям не обращается.
 *
 * Если ваш код не удовлетворяет всем трём - ЗАВЕДИТЕ СВОЙ БУФЕР.
 * Нарушение даст не отказ, а тихую порчу данных на чужом переносе,
 * которую крайне тяжело локализовать.
 *
 * Заголовок намеренно не включён в mem.h: тот тянется почти всем
 * деревом, и extern в нём провоцировал бы переиспользование из
 * контекстов, где условия выше не выполняются.
 *
 * Определение - в pc.c.
 */
#define GUEST_BULK_BUF_SIZE 512
extern uint8_t guest_bulk_buf[GUEST_BULK_BUF_SIZE];

#endif /* BULK_BOUNCE_H */
